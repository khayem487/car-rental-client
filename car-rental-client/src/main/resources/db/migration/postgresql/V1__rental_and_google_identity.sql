-- First durable PostgreSQL schema. Flyway refuses a nonempty unversioned schema.
CREATE TABLE personne (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cin VARCHAR(20) UNIQUE NOT NULL,
    nom VARCHAR(50) NOT NULL,
    prenom VARCHAR(50) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    npermis VARCHAR(20) NOT NULL,
    nbloc INTEGER NOT NULL DEFAULT 0,
    login VARCHAR(50) UNIQUE NOT NULL,
    passwd VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CLIENT', 'ADMIN'))
);
CREATE TABLE oidc_identity (
    provider VARCHAR(20) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    personne_id BIGINT NOT NULL UNIQUE REFERENCES personne(id),
    email VARCHAR(320) NOT NULL,
    PRIMARY KEY (provider, subject)
);
CREATE TABLE voiture (
    mat VARCHAR(20) PRIMARY KEY,
    marque VARCHAR(50) NOT NULL,
    model VARCHAR(50) NOT NULL,
    nbplace INTEGER NOT NULL CHECK (nbplace > 0),
    disp VARCHAR(20) NOT NULL CHECK (disp IN ('DISPONIBLE', 'LOUEE', 'PANNE')),
    nbloc INTEGER NOT NULL DEFAULT 0,
    prix NUMERIC(10,2) NOT NULL CHECK (prix >= 0),
    image_path VARCHAR(255) NOT NULL DEFAULT 'default.jpg'
);
CREATE TABLE location (
    id_location BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personne BIGINT NOT NULL REFERENCES personne(id),
    mat VARCHAR(20) NOT NULL REFERENCES voiture(mat),
    dteDeb DATE NOT NULL,
    duree INTEGER NOT NULL CHECK (duree BETWEEN 1 AND 30),
    cheque VARCHAR(50) NOT NULL,
    etat VARCHAR(20) NOT NULL CHECK (etat IN ('EN_COURS', 'TERMINEE'))
);
CREATE INDEX idx_voiture_disp ON voiture(disp);
CREATE INDEX idx_location_personne ON location(id_personne);
CREATE INDEX idx_location_etat ON location(etat);
-- Database protection supplements the application's atomic claim transaction.
CREATE UNIQUE INDEX one_active_rental_per_car ON location(mat) WHERE etat = 'EN_COURS';
